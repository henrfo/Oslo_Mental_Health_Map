"""
Fetches the bydel → DPS catchment mapping for Oslo from SSB's classification
API (KLASS) and writes it to _data/dps.yml.

Source: KLASS classification 632, "Kodeliste for opptaksområder i
spesialisthelsetjenesten (DPS)". SSB publishes a new version each year, so
rerun this when a new year's version appears. The script always picks the
version that is valid today.

Uses two correspondence tables of that version:
  - DPS → Bydelsinndeling: which Oslo bydeler each DPS covers
  - DPS → Kommuneinndeling: other kommuner in the same DPS area (e.g. Nittedal)

Note: SSB defines the areas at grunnkrets level. At bydel level every Oslo
bydel maps to exactly one DPS, which is what the map needs; a few grunnkretser
in bydel Sentrum are split between DPS areas and are not represented here.
"""

from __future__ import annotations

import json
import sys
import urllib.request
from collections import defaultdict
from datetime import date
from pathlib import Path

KLASS = 'https://data.ssb.no/api/klass/v1'
CLASSIFICATION_ID = 632
OSLO_BYDEL_PREFIX = '0301'
OUT = Path(__file__).resolve().parent.parent / '_data' / 'dps.yml'


def get(url: str) -> dict:
    req = urllib.request.Request(url, headers={'Accept': 'application/json'})
    with urllib.request.urlopen(req, timeout=60) as resp:
        return json.load(resp)


def current_version() -> dict:
    """Return the version of the classification that is valid today."""
    today = date.today().isoformat()
    versions = get(f'{KLASS}/classifications/{CLASSIFICATION_ID}')['versions']
    for v in versions:
        if v['validFrom'] <= today and (v.get('validTo') is None or today < v['validTo']):
            return get(v['_links']['self']['href'])
    sys.exit(f'No version of KLASS {CLASSIFICATION_ID} is valid for {today}')


def correspondence(version: dict, target_word: str) -> list[dict]:
    """Return the maps of the correspondence table whose name mentions target_word."""
    for table in version['correspondenceTables']:
        if target_word in table['name']:
            return get(table['_links']['self']['href'])['correspondenceMaps']
    sys.exit(f'No "{target_word}" correspondence table in {version["name"]}')


def quote(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def main() -> None:
    version = current_version()
    items = {i['code']: i for i in version['classificationItems']}

    bydeler = defaultdict(list)
    for m in correspondence(version, 'Bydelsinndeling'):
        if m['targetCode'].startswith(OSLO_BYDEL_PREFIX):
            bydeler[m['sourceCode']].append(m['targetName'])

    outside_oslo = defaultdict(list)
    for m in correspondence(version, 'Kommuneinndeling'):
        if m['sourceCode'] in bydeler and not m['targetName'].startswith('Oslo'):
            outside_oslo[m['sourceCode']].append(m['targetName'])

    lines = [
        '# Bydel → DPS opptaksområde (catchment area) for Oslo.',
        '# GENERATED by scripts/update_dps.py — do not edit by hand; rerun the script.',
        f'# Source: SSB KLASS {CLASSIFICATION_ID}, "{version["name"]}"',
        f'#   https://www.ssb.no/klass/klassifikasjoner/{CLASSIFICATION_ID}',
        '# "Sentrum" and "Marka" are SSB statistical bydeler, not administrative ones.',
        f'version: {quote(version["name"])}',
        f'valid_from: {version["validFrom"]}',
        f'fetched: {date.today().isoformat()}',
        'areas:',
    ]
    for code in sorted(bydeler, key=lambda c: items[c]['name']):
        dps = items[code]
        hf = items.get(dps.get('parentCode'), {})
        lines += [
            f'  - code: {code}',
            f'    dps: {quote(dps["name"] + " DPS")}',
            f'    helseforetak: {quote(hf.get("name", ""))}',
            f'    bydeler: [{", ".join(quote(b) for b in bydeler[code])}]',
            f'    outside_oslo: [{", ".join(quote(k) for k in outside_oslo[code])}]',
        ]

    OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'Wrote {len(bydeler)} DPS areas from "{version["name"]}" to {OUT}')


if __name__ == '__main__':
    main()
